export function generateProgramFromForm(formData: EnrollmentFormData): EnrolledProgramCardData {
  const isK12 = formData.institutionTierId.toLowerCase().includes('k12') || formData.institutionTierId.toLowerCase().includes('elementary');
  const title = isK12
    ? `${formData.levelQualificationId} Program`
    : `${formData.levelQualificationId} in ${formData.fieldOfStudy || 'General Studies'}`;

  const isFullTime = formData.schedule.studyPace === 'full_time';
  
  return {
    id: `prog_${Date.now()}`,
    programTitle: title,
    institutionName: formData.institutionName,
    language: formData.language,
    countryName: formData.countryCode,
    countryFlag: '🌐',
    tierTitle: formData.institutionTierId,
    levelTitle: formData.levelQualificationId,
    fieldOfStudy: formData.fieldOfStudy,
    studyPace: formData.schedule.studyPace,
    dateOfBirth: formData.dateOfBirth,
    educationLevel: formData.educationLevel,
    countryOfOrigin: formData.countryOfOrigin,
    maritalStatus: formData.maritalStatus, 
    employmentStatus: formData.employmentStatus, 
    currentRoleOrExperience: formData.currentRoleOrExperience,
    externalCoursesCompleted: formData.externalCoursesCompleted,
    careerBio: formData.careerBio,
    hoursPerDay: formData.schedule.hoursPerDay,
    lecturesPerDay: formData.schedule.lecturesPerDay,
    lectureDurationMinutes: formData.schedule.lectureDurationMinutes,
    selectedDays: formData.schedule.selectedDays,
    enrollmentDate: new Date().toISOString().split('T')[0],
    estimatedGraduationDate: isFullTime ? '2028-08-30' : '2029-12-20',
    completionPercentage: 0,
    totalSemestersOrSessions: isK12 ? 2 : 6,
    currentSemester: 1,
    totalSessions:4,
    completedSessions:1,
    totalCreditsRequired: isK12 ? 60 : 120,
    creditsEarned: 0,
    programDescription: formData.careerBio || 'A custom-designed academic curriculum tailored to individual professional goals and industry competencies.',
    scheduleSummary: isFullTime
      ? 'Full-Time Dynamic Schedule (Mon - Fri | 4.5 hrs/day | 3 Lectures/day)'
      : `Part-Time Flexible (${formData.schedule.selectedDays?.join(', ') || 'Custom'} | ${formData.schedule.lecturesPerDay || 2} Lec/day)`,
    aiCurriculumBreakdown: [
      {
        semesterNumber: 1,
        title: 'Semester I: Core Fundamentals & Theory',
        totalLectures: 18,
        coreModules: ['Introduction to Discipline Methods', 'Applied Mathematics & Analysis', 'Academic Writing & Research', 'System Design Tools']
      },
      {
        semesterNumber: 2,
        title: 'Semester II: Intermediate Specialization',
        totalLectures: 18,
        coreModules: ['Advanced Topics & Implementation', 'Practical Laboratory & Studio', 'Domain Case Studies', 'Collaborative Project Work']
      }
    ],
    prerequisitesMet: [formData.educationLevel, ...(formData.externalCoursesCompleted ? [formData.externalCoursesCompleted] : [])],
    careerPathways: ['Domain Industry Leader', 'Technical Specialist', 'Academic Researcher']
  };
}